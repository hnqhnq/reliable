#!/usr/bin/env python3
"""Aggregate metrics from planned API experiment run directories."""

from __future__ import annotations

import json
import re
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path("/home/src/Reliable")
OUT = ROOT / "runs/planned_api_experiments/evaluation_summary.md"

HAMMING = re.compile(
    r"\((after CD|after LLM \+ RAG|after fix)\) structural hamming distance:\s*\(([^,]+),\s*([^)]+)\)"
)
Y_ACC = re.compile(r"test/y/y_accuracy\s+([\d.]+)")


@dataclass
class C2BMRun:
    provider: str
    seed: int
    run_dir: Path
    hamming: dict[str, tuple[float, float]]
    y_accuracy: float | None
    prompt_tokens: int
    completion_tokens: int
    api_calls: int


def parse_train_log(path: Path) -> tuple[dict[str, tuple[float, float]], float | None]:
    hamming: dict[str, tuple[float, float]] = {}
    y_acc: float | None = None
    if not path.is_file():
        return hamming, y_acc
    text = path.read_text(encoding="utf-8", errors="replace")
    for m in HAMMING.finditer(text):
        hamming[m.group(1)] = (float(m.group(2)), float(m.group(3)))
    accs = Y_ACC.findall(text)
    if accs:
        y_acc = float(accs[-1])
    return hamming, y_acc


def sum_usage(jsonl: Path) -> tuple[int, int, int]:
    prompt = completion = calls = 0
    if not jsonl.is_file():
        return prompt, completion, calls
    for line in jsonl.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if row.get("event") != "response":
            continue
        usage = row.get("usage") or {}
        prompt += int(usage.get("prompt_tokens") or 0)
        completion += int(usage.get("completion_tokens") or 0)
        calls += 1
    return prompt, completion, calls


def collect_c2bm(provider: str, seed: int) -> C2BMRun:
    run_dir = ROOT / f"runs/c2bm/asia_predicted_{provider}_seed{seed}"
    hamming, y_acc = parse_train_log(run_dir / "train.log")
    p, c, n = sum_usage(run_dir / "requests.jsonl")
    return C2BMRun(provider, seed, run_dir, hamming, y_acc, p, c, n)


def mean_2sem(values: list[float]) -> str:
    """Paper-style mean ± 2SEM (same convention as local true-graph runs)."""
    if not values:
        return "—"
    if len(values) == 1:
        return f"{values[0]:.2f}% (n=1)"
    m = statistics.mean(values)
    s = statistics.stdev(values)
    sem2 = 2.0 * s / (len(values) ** 0.5)
    return f"{m:.2f} ± {sem2:.2f}% (n={len(values)})"


def main() -> int:
    providers = ("qwen", "deepseek")
    seeds = [1, 2, 3, 4, 5]
    def status_of(path: Path) -> str:
        p = path / "status.txt"
        return p.read_text(encoding="utf-8").strip() if p.is_file() else "—"

    runs: list[C2BMRun] = []
    for provider in providers:
        for seed in seeds:
            r = collect_c2bm(provider, seed)
            if status_of(r.run_dir) == "SUCCEEDED" or r.hamming or r.y_accuracy:
                runs.append(r)

    bc_csv = ROOT / "runs/bc-llm/cub_api_smoke_qwen/results.csv"
    bc_line = ""
    if bc_csv.is_file():
        bc_line = bc_csv.read_text(encoding="utf-8").strip().splitlines()[-1]

    lines = [
        "# Planned API experiments — evaluation summary",
        "",
        f"Generated by `{Path(__file__).name}`. Re-run after multiseed training finishes.",
        "",
        "## C²BM Asia (predicted graph + LLM + RAG)",
        "",
        "Paper reference (GPT-4o, Table 9): SHD **0.25**, wrong directed edges **1**, task acc **71.4 ± 1.7%** (5 seeds).",
        "Local true-graph Asia (2026-10-02): **71.15 ± 1.98%**.",
        "",
        "| Provider | Seed | Status | SHD (after fix) | Wrong edges | Task acc | API calls | Prompt tok | Completion tok |",
        "|---|---:|---|---:|---:|---:|---:|---:|---:|",
    ]

    for provider in providers:
        for seed in seeds:
            run_dir = ROOT / f"runs/c2bm/asia_predicted_{provider}_seed{seed}"
            status = status_of(run_dir)
            r = collect_c2bm(provider, seed)
            fix = r.hamming.get("after fix") or r.hamming.get("after LLM + RAG")
            shd = f"{fix[0]:.2f}" if fix else "—"
            wrong = f"{fix[1]:.0f}" if fix else "—"
            acc = f"{r.y_accuracy * 100:.2f}%" if r.y_accuracy is not None else "—"
            lines.append(
                f"| {provider} | {seed} | {status} | {shd} | {wrong} | {acc} | {r.api_calls} | {r.prompt_tokens} | {r.completion_tokens} |"
            )

    lines.extend(["", "### Aggregated task accuracy (mean ± 2SEM, succeeded seeds 1–5)", ""])
    for provider in providers:
        accs = [
            r.y_accuracy
            for r in runs
            if r.provider == provider and r.y_accuracy is not None
            and status_of(r.run_dir) == "SUCCEEDED"
        ]
        lines.append(f"- **{provider}**: {mean_2sem([a * 100 for a in accs])}")
    lines.append(
        "- **Note**: Qwen and DeepSeek share the same completed graph per seed index "
        "(identical downstream numbers are expected)."
    )

    lines.extend(
        [
            "",
            "## BC-LLM CUB API smoke (40 images, not paper scale)",
            "",
            f"Last row of `results.csv`: `{bc_line}`" if bc_line else "_No results.csv yet._",
            "",
            "## Acceptance (seed 1 vs paper)",
            "",
        ]
    )

    for provider in providers:
        r = collect_c2bm(provider, 1)
        fix = r.hamming.get("after fix")
        llm = r.hamming.get("after LLM + RAG")
        ok_shd = fix and fix[0] == 0.25 and fix[1] == 1.0
        ok_acc = r.y_accuracy is not None and abs(r.y_accuracy - 0.714) <= 0.05
        lines.append(
            f"- **{provider} seed 1**: SHD/edges after LLM={llm}, after fix={fix}; "
            f"task acc={r.y_accuracy}; graph match paper={'yes' if ok_shd else 'check'}; "
            f"acc within ~5pp of 71.4%={'yes' if ok_acc else 'check'}."
        )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
